create table vnd_cidades (
  id        number primary key,
  descricao varchar2(80) not null
);

create table vnd_clientes (
  id             number primary key,
  nome           varchar2(100) not null,
  cpf            varchar2(14),
  email          varchar2(120),
  cidade_id      number references vnd_cidades,
  limite_credito number default 0,
  dt_cadastro    date default sysdate
);

create table vnd_categorias (
  id   number primary key,
  nome varchar2(60) not null
);

create table vnd_fornecedores (
  id           number primary key,
  razao_social varchar2(120) not null,
  ativo        varchar2(1) default 'S'
);

create table vnd_produtos (
  id            number primary key,
  codigo        varchar2(20),
  descricao     varchar2(400) not null,
  categoria_id  number references vnd_categorias,
  fornecedor_id number references vnd_fornecedores,
  unidade       varchar2(2) default 'UN',
  preco_custo   number(12,2),
  preco_venda   number(12,2),
  ativo         varchar2(1) default 'S',
  dt_cadastro   date default trunc(sysdate),
  usuario_alt   varchar2(30),
  dt_alt        date
);

create table vnd_estoque (
  id          number primary key,
  produto_id  number not null references vnd_produtos,
  deposito    varchar2(1),
  quantidade  number,
  dt_mov      date default trunc(sysdate),
  usuario_alt varchar2(30)
);

create table vnd_compras (
  id         number generated by default as identity primary key,
  produto_id number references vnd_produtos,
  custo      number(12,2),
  data       date
);

create table vnd_historico_precos (
  id             number primary key,
  produto_id     number references vnd_produtos,
  dt_alteracao   date,
  preco_anterior number(12,2),
  preco_novo     number(12,2),
  usuario        varchar2(30)
);

create table vnd_pedidos (
  numero      number primary key,
  dt_pedido   date default trunc(sysdate) not null,
  cliente_id  number not null references vnd_clientes,
  status      varchar2(1) default 'A',
  desconto    number(5,2) default 0,
  valor_total number(12,2),
  usuario     varchar2(30)
);

create table vnd_itens_pedido (
  id          number primary key,
  pedido_id   number not null references vnd_pedidos,
  produto_id  number not null references vnd_produtos,
  quantidade  number not null,
  preco_unit  number(12,2)
);

create table vnd_dept (
  deptno number(2) primary key,
  dname  varchar2(14),
  loc    varchar2(13)
);

create table vnd_emp (
  empno    number(4) primary key,
  ename    varchar2(10),
  job      varchar2(9),
  mgr      number(4),
  sal      number(7,2),
  hiredate date,
  deptno   number(2) references vnd_dept
);

create sequence vnd_clientes_seq start with 100;
create sequence vnd_produtos_seq start with 100;
create sequence vnd_estoque_seq start with 100;
create sequence vnd_pedidos_seq start with 5000;
create sequence vnd_itens_pedido_seq start with 100;

-- usada pela validação de CPF do form CLIENTES
create or replace package vnd_util as
  function cpf_valido(p_cpf varchar2) return boolean;
end vnd_util;
/
create or replace package body vnd_util as
  function cpf_valido(p_cpf varchar2) return boolean is
    d varchar2(11) := regexp_replace(p_cpf, '[^0-9]', '');
    s number;
    r number;
  begin
    if p_cpf is null then return true; end if;
    if length(d) <> 11 or d = lpad(substr(d, 1, 1), 11, substr(d, 1, 1)) then return false; end if;
    for k in 9 .. 10 loop
      s := 0;
      for i in 1 .. k loop
        s := s + to_number(substr(d, i, 1)) * (k + 2 - i);
      end loop;
      r := mod(s * 10, 11);
      if r = 10 then r := 0; end if;
      if r <> to_number(substr(d, k + 1, 1)) then return false; end if;
    end loop;
    return true;
  end cpf_valido;
end vnd_util;
/

